let currentLang: Language = 'fa'
const listeners: Array<(lang: Language) => void> = []

export function getLanguage(): Language {
  const saved = localStorage.getItem('nexvpn_lang') as Language
  if (saved === 'fa' || saved === 'en') {
    currentLang = saved
  } else {
    currentLang = 'fa'
  }
  return currentLang
}

export function setLanguage(lang: Language) {
  currentLang = lang
  localStorage.setItem('nexvpn_lang', lang)
  document.documentElement.setAttribute('lang', lang)
  document.documentElement.setAttribute('dir', lang === 'fa' ? 'rtl' : 'ltr')
  listeners.forEach(l => l(lang))
}

export function t(key: keyof typeof translations['en'] | string, params?: Record<string, string | number>): string {
  const lang = getLanguage()
  let str = (translations[lang] as any)?.[key] || (translations['en'] as any)?.[key] || key
  if (params && typeof str === 'string') {
    Object.keys(params).forEach(p => {
      str = str.replace(new RegExp(`\\{${p}\\}`, 'g'), String(params[p]))
    })
  }
  return str
}

export function onLanguageChange(cb: (lang: Language) => void) {
  listeners.push(cb)
  return () => {
    const idx = listeners.indexOf(cb)
    if (idx !== -1) listeners.splice(idx, 1)
  }
}
