let currentLang: Language = 'fa'
const listeners: Array<(lang: Language) => void> = []

// applyLanguageDirection mirrors the language onto the document element.
// Deliberately separate from getLanguage: that function is called by t(), and
// t() runs several times per rendered element — writing two attributes on
// documentElement on every one of those calls forces a style recalculation each
// time, which is the whole reason this was moved out of the read path.
function applyLanguageDirection(lang: Language) {
  if (typeof document === 'undefined') return
  document.documentElement.setAttribute('lang', lang)
  document.documentElement.setAttribute('dir', lang === 'fa' ? 'rtl' : 'ltr')
}

// syncLanguageFromStorage resolves the language from storage and applies it.
// Runs once on module load, and again on every setLanguage.
function syncLanguageFromStorage(): Language {
  if (typeof window === 'undefined') return currentLang
  const saved = localStorage.getItem('nexvpn_lang') as Language
  currentLang = saved === 'fa' || saved === 'en' ? saved : 'fa'
  applyLanguageDirection(currentLang)
  return currentLang
}

